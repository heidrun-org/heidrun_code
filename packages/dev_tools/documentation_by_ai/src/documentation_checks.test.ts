import Test from 'node:test';
import Assert from 'node:assert/strict';
import Fs from 'node:fs';
import Os from 'node:os';
import Path from 'node:path';
import { DocumentationChecks } from './documentation_checks.ts';
import { DocumentationHints } from './documentation_hints.ts';
import { DocumentationGeneration } from './documentation_generation.ts';
import { DocumentationProcess } from './documentation_process.ts';
import { DocumentationUpdate } from './documentation_update.ts';

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
//	DocumentationChecksTest — exercises history, provenance and publication refusal
///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

/** Creates real small Git histories for the updater's pre-publication checks. */
class DocumentationChecksTest {
	/**
	 * Creates a repository with one current rule and a generated page.
	 * @returns A temporary checkout, removed by the test cleanup.
	 */
	static fixture(): string {
		const root = Fs.mkdtempSync(Path.join(Os.tmpdir(), 'documentation-checks-'));
		Test.after(() => Fs.rmSync(root, {
			recursive: true,
			force: true,
		}));
		DocumentationChecks.command(root, 'git', ['init', '-b', 'dev_jerome']);
		DocumentationChecks.command(root, 'git', ['config', 'user.name', 'Documentation test']);
		DocumentationChecks.command(root, 'git', ['config', 'user.email', 'test@example.com']);
		DocumentationChecks.command(root, 'git', ['remote', 'add', 'origin', 'https://github.com/example/docs.git']);
		Fs.mkdirSync(Path.join(root, 'docs/agents_rules/user_interface'), {
			recursive: true,
		});
		Fs.mkdirSync(Path.join(root, DocumentationChecks.pagesPath), {
			recursive: true,
		});
		Fs.writeFileSync(Path.join(root, 'docs/agents_rules/user_interface/task.md'), 'Current feature');
		Fs.mkdirSync(Path.join(root, 'docs/agents_rules/glossary'));
		Fs.writeFileSync(Path.join(root, 'docs/agents_rules/glossary/index.md'), 'Current terms');
		Fs.writeFileSync(Path.join(root, DocumentationChecks.pagesPath, 'task.md'),
			'# Do a task\n<!-- generated by docs:update_by_ai -->\n## Steps\n'
			+ '<!-- source: docs/agents_rules/user_interface/task.md -->\n1. Do the task.\n');
		DocumentationChecksTest.commit(root, 'Initial source');
		return root;
	}

	/**
	 * Records a fixture revision without a remote operation.
	 * @param root Temporary repository.
	 * @param message Commit subject.
	 * @returns Full revision identifier for history tests.
	 */
	static commit(root: string, message: string): string {
		DocumentationChecks.command(root, 'git', ['add', '.']);
		DocumentationChecks.command(root, 'git', ['commit', '-m', message]);
		return DocumentationChecks.command(root, 'git', ['rev-parse', 'HEAD']);
	}
}

Test.test('rejects a real commit on a disconnected history', () => {
	const root = DocumentationChecksTest.fixture();
	DocumentationChecks.command(root, 'git', ['checkout', '--orphan', 'other-history']);
	const unrelated = DocumentationChecksTest.commit(root, 'Unrelated history');
	DocumentationChecks.command(root, 'git', ['checkout', 'dev_jerome']);
	Fs.writeFileSync(Path.join(root, DocumentationChecks.markerPath), unrelated);
	Assert.throws(() => DocumentationChecks.previousCommit(root));
});

Test.test('rejects a page whose generated ownership mark was removed', () => {
	const root = DocumentationChecksTest.fixture();
	const page = Path.join(root, DocumentationChecks.pagesPath, 'task.md');
	Fs.writeFileSync(page, Fs.readFileSync(page, 'utf8').replace('<!-- generated by docs:update_by_ai -->', ''));
	Assert.throws(() => DocumentationChecks.pages(root), /no generated mark/);
});

Test.test('rejects a page still naming a removed source rule', () => {
	const root = DocumentationChecksTest.fixture();
	Fs.unlinkSync(Path.join(root, 'docs/agents_rules/user_interface/task.md'));
	Assert.throws(() => DocumentationChecks.pages(root), /Missing or invalid source/);
});

Test.test('collects every commit between known revisions, including changes without a pull request', () => {
	const root = DocumentationChecksTest.fixture();
	const previous = DocumentationChecks.command(root, 'git', ['rev-parse', 'HEAD']);
	Fs.writeFileSync(Path.join(root, 'docs/agents_rules/user_interface/task.md'), 'Changed behavior');
	DocumentationChecksTest.commit(root, 'Change visible behavior');
	Fs.writeFileSync(Path.join(root, 'internal.txt'), 'Internal change');
	DocumentationChecksTest.commit(root, 'Internal maintenance');
	const hints = DocumentationHints.collect(root, previous);
	Assert.match(hints, /Change visible behavior/);
	Assert.match(hints, /Internal maintenance/);
	Assert.match(hints, /Changed behavior/);
	Assert.doesNotMatch(hints, /Initial source/);
});

Test.test('first run has no history hints and valid generated sources pass', () => {
	const root = DocumentationChecksTest.fixture();
	Assert.equal(DocumentationChecks.previousCommit(root), undefined);
	Assert.match(DocumentationHints.collect(root), /First run/);
	Assert.doesNotThrow(() => DocumentationChecks.pages(root));
});

Test.test('adds merged pull request context and only its closed issues to all-commit hints', () => {
	const root = DocumentationChecksTest.fixture();
	const previous = DocumentationChecks.command(root, 'git', ['rev-parse', 'HEAD']);
	Fs.writeFileSync(Path.join(root, 'internal.txt'), 'Change');
	DocumentationChecksTest.commit(root, 'Merge feature (#17)');
	const commandFn = DocumentationChecks.command.bind(DocumentationChecks);
	Test.mock.method(DocumentationChecks, 'command', (cwd: string, command: string, args: string[]) => {
		if (command === 'gh' && args[0] === 'pr') {
			return JSON.stringify({
				title: 'Merged feature context',
				body: 'Fixes #18. Fixes #19.',
				state: 'MERGED',
				closingIssuesReferences: [],
			});
		}
		if (command === 'gh') {
			return JSON.stringify({
				title: args[2] === '18' ? 'Closed feature defect' : 'Still open follow-up',
				state: args[2] === '18' ? 'CLOSED' : 'OPEN',
			});
		}
		return commandFn(cwd, command, args);
	});
	try {
		const hints = DocumentationHints.collect(root, previous);
		Assert.match(hints, /Merged feature context/);
		Assert.match(hints, /Closed feature defect/);
		Assert.doesNotMatch(hints, /Still open follow-up/);
	} finally {
		Test.mock.restoreAll();
	}
});

Test.test('refuses shortcuts, unrelated source and symbolic-link publication', () => {
	const root = DocumentationChecksTest.fixture();
	const shortcut = Path.join(root, DocumentationChecks.pagesPath, 'shortcuts.md');
	Fs.writeFileSync(shortcut, 'Changed shortcut');
	Assert.throws(() => DocumentationChecks.publicationFiles(root), /out-of-scope/);
	Fs.unlinkSync(shortcut);
	Fs.writeFileSync(Path.join(root, 'internal.txt'), 'Unrelated source');
	Assert.throws(() => DocumentationChecks.publicationFiles(root), /out-of-scope/);
	Fs.unlinkSync(Path.join(root, 'internal.txt'));
	Fs.symlinkSync(Path.join(root, 'docs/agents_rules/user_interface/task.md'),
		Path.join(root, DocumentationChecks.pagesPath, 'linked.md'));
	Assert.throws(() => DocumentationChecks.publicationFiles(root), /out-of-scope/);
});

for (const isTestFailure of [true, false]) {
	Test.test(`full update ${isTestFailure ? 'never publishes after failed tests' : 'publishes only a checked draft'}`,
		async () => {
			const root = DocumentationChecksTest.fixture();
			const originalRoot = DocumentationGeneration.repositoryPath;
			const commandFn = DocumentationChecks.command.bind(DocumentationChecks);
			const head = commandFn(root, 'git', ['rev-parse', 'HEAD']);
			let worktree = '';
			let isPushed = false;
			let isDraftCreated = false;
			Object.defineProperty(DocumentationGeneration, 'repositoryPath', {
				value: root,
				configurable: true,
			});
			Test.mock.method(DocumentationChecks, 'command', (cwd: string, command: string, args: string[]) => {
				if (command === 'git' && args[0] === 'worktree') {
					const branch = commandFn(worktree, 'git', ['branch', '--show-current']);
					return `worktree ${worktree}\nbranch refs/heads/${branch}`;
				}
				if (command === 'git' && args[0] === 'push') {
					isPushed = true;
					return '';
				}
				if (command === 'gh') {
					Assert.ok(args.includes('--draft'));
					Assert.ok(args.includes('--body-file'));
					isDraftCreated = true;
					return 'https://github.com/example/docs/pull/1';
				}
				return commandFn(cwd, command, args);
			});
			Test.mock.method(DocumentationProcess, 'run', async (_command: string, args: string[]) => {
				if (args[0] === 'worktree:create') {
					worktree = `${root}-generated`;
					commandFn(root, 'git', ['clone', '--quiet', root, worktree]);
					commandFn(worktree, 'git', ['checkout', '-b', args[1]]);
					commandFn(worktree, 'git', ['config', 'user.name', 'Documentation test']);
					commandFn(worktree, 'git', ['config', 'user.email', 'test@example.com']);
					Test.after(() => Fs.rmSync(worktree, {
						recursive: true,
						force: true,
					}));
				} else if (isTestFailure === true) {
					throw new Error('Website tests failed');
				}
			});
			Test.mock.method(DocumentationGeneration, 'run', async () => {
				const runPath = Path.join(worktree, 'run');
				Fs.mkdirSync(runPath);
				Fs.writeFileSync(Path.join(runPath, 'answer.md'), 'Changed: task instructions.');
				Fs.writeFileSync(Path.join(worktree, '.git/info/exclude'), 'run\n');
				return runPath;
			});
			try {
				const options = {
					model: 'test-only',
					effort: 'medium' as const,
					onlyRuleFiles: [],
					isDryRun: false,
				};
				if (isTestFailure === true) {
					await Assert.rejects(DocumentationUpdate.run(options), /Website tests failed/);
					Assert.equal(Fs.existsSync(Path.join(worktree, DocumentationChecks.markerPath)), false);
				} else {
					Assert.equal(await DocumentationUpdate.run(options), 'https://github.com/example/docs/pull/1');
					Assert.equal(Fs.readFileSync(Path.join(worktree, DocumentationChecks.markerPath), 'utf8'),
						`${head}\n`);
				}
				Assert.equal(isPushed, isTestFailure === false);
				Assert.equal(isDraftCreated, isTestFailure === false);
				Assert.equal(commandFn(root, 'git', ['rev-parse', 'HEAD']), head);
			} finally {
				Test.mock.restoreAll();
				Object.defineProperty(DocumentationGeneration, 'repositoryPath', {
					value: originalRoot,
					configurable: true,
				});
			}
		});
}
