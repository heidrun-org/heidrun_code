import Fs from 'node:fs';
import Path from 'node:path';
import ChildProcess from 'node:child_process';

///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////
//	DocumentationChecks — checks provenance and publication boundaries
///////////////////////////////////////////////////////////////////////////////
///////////////////////////////////////////////////////////////////////////////

/** Validates documentation before any Git publication. */
export class DocumentationChecks {
	/** Repository-relative directory owned by the documentation writer. */
	static readonly pagesPath = 'packages/auxiliary/website_public/docs/documentation';
	/** Last source revision successfully documented and checked. */
	static readonly markerPath = `${DocumentationChecks.pagesPath}/.last_documented_commit`;

	/**
	 * Runs an argument-array command and reports a nonzero exit.
	 * @param root Checkout in which to run the command.
	 * @param command Program name.
	 * @param args Arguments passed without a shell.
	 * @returns Standard output without surrounding whitespace.
	 */
	static command(root: string, command: string, args: string[]): string {
		return ChildProcess.execFileSync(command, args, {
			cwd: root,
			encoding: 'utf8',
			maxBuffer: 64 * 1024 * 1024,
		}).trim();
	}

	/**
	 * Rejects a marker outside the current history, including malformed revisions.
	 * @param root Checkout to inspect.
	 * @returns The previous revision, or undefined for the first run.
	 */
	static previousCommit(root: string): string | undefined {
		const path = Path.join(root, DocumentationChecks.markerPath);
		if (Fs.existsSync(path) === false) {
			return undefined;
		}
		const commit = Fs.readFileSync(path, 'utf8').trim();
		if (/^[a-f0-9]{40,64}$/.test(commit) === false) {
			throw new Error('The last documented commit must be a full Git commit identifier.');
		}
		DocumentationChecks.command(root, 'git', ['merge-base', '--is-ancestor', commit, 'HEAD']);
		return commit;
	}

	/**
	 * Checks generated marks and source references on every documentation page except shortcuts.
	 * @param root Checkout whose pages have been generated.
	 * @returns Nothing when all pages meet the ownership and source requirements.
	 */
	static pages(root: string): void {
		for (const file of Fs.readdirSync(Path.join(root, DocumentationChecks.pagesPath), {
			recursive: true,
			encoding: 'utf8',
		})) {
			if (file.endsWith('.md') === false || file === 'shortcuts.md') {
				continue;
			}
			const text = Fs.readFileSync(Path.join(root, DocumentationChecks.pagesPath, file), 'utf8');
			if (text.includes('<!-- generated by docs:update_by_ai -->') === false) {
				throw new Error(`Documentation page has no generated mark: ${file}`);
			}
			for (const match of text.matchAll(/<!-- source:\s*(.*?)\s*-->/g)) {
				const source = match[1];
				const path = Path.resolve(root, source);
				if (Path.isAbsolute(source) || path.startsWith(`${root}${Path.sep}`) === false
					|| Fs.existsSync(path) === false
					|| Fs.realpathSync(path).startsWith(`${Fs.realpathSync(root)}${Path.sep}`) === false
					|| Fs.statSync(path).isFile() === false) {
					throw new Error(`Missing or invalid source in ${file}: ${source}`);
				}
			}
			for (const section of text.split(/^## /m).slice(1)) {
				if (section.startsWith('Related pages') === false && /<!-- source: .+? -->/.test(section) === false) {
					throw new Error(`Section has no source in ${file}: ${section.split('\n')[0]}`);
				}
			}
		}
	}

	/**
	 * Lists changed tracked and untracked files without treating renames as one combined name.
	 * @param root Checkout to inspect.
	 * @returns Changed repository-relative paths.
	 */
	static changed(root: string): string[] {
		const tracked = DocumentationChecks.command(root, 'git', ['diff', '--name-only', '--no-renames', '-z', 'HEAD']);
		const added = DocumentationChecks.command(root, 'git', ['ls-files', '--others', '--exclude-standard', '-z']);
		return [...new Set([...tracked.split('\0'), ...added.split('\0')].filter((file) => file !== ''))];
	}

	/**
	 * Refuses source, shortcuts, identity, publishing and other unrelated changes before staging.
	 * @param root Checkout receiving generated changes.
	 * @returns Paths that may be committed.
	 */
	static publicationFiles(root: string): string[] {
		const files = DocumentationChecks.changed(root);
		const website = 'packages/auxiliary/website_public/docs/';
		for (const file of files) {
			const isAllowed = file.startsWith(`${DocumentationChecks.pagesPath}/`)
				&& (file.endsWith('.md') || file === DocumentationChecks.markerPath)
				&& file !== `${DocumentationChecks.pagesPath}/shortcuts.md`
				|| file.startsWith(`${website}public/documentation_images/`)
				|| ['.vitepress/config.ts', '.vitepress/theme/index.ts', '.vitepress/theme/troubleshooting_panels.ts',
					'.vitepress/theme/troubleshooting.css'].some((path) => file === `${website}${path}`);
			if (isAllowed === false || Fs.existsSync(Path.join(root, file))
				&& Fs.lstatSync(Path.join(root, file)).isSymbolicLink()) {
				throw new Error(`Refusing to publish an out-of-scope file: ${file}`);
			}
		}
		return files;
	}
}
